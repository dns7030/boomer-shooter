// Writes src/version.js (build number = commit count + 1, and the time). Run before each commit:  node tools/stamp.mjs
import { execSync } from 'node:child_process';
import fs from 'node:fs';
const n = Number(execSync('git rev-list --count HEAD').toString().trim()) + 1;
fs.writeFileSync(new URL('../src/version.js', import.meta.url), `// generated by tools/stamp.mjs\nexport const BUILD = { n: ${n}, time: '${new Date().toISOString()}' };\n`);
console.log('stamped build', n);
